#!/usr/bin/env bash
# Update app containers; one reviewed pinned-WAHA IPv4 transition is allowed below.
# Never recreate the database, change persistent volumes or delete stored data.
set -euo pipefail
umask 077
target=/opt/omnicrm-pilot
backup_root=/opt/omnicrm-pilot-updates
fail() { printf '%s\n' "$*" >&2; exit 1; }
[ "$(id -u)" = 0 ] || fail 'Run this updater as root on the target server.'
for command in python3 docker flock sha256sum df awk; do
  command -v "$command" >/dev/null 2>&1 || fail "Required command is missing: $command"
done
[ -d "$target" ] && [ ! -L "$target" ] || fail 'An existing real /opt/omnicrm-pilot directory is required.'
[ -f "$target/.env.pilot" ] && [ ! -L "$target/.env.pilot" ] || fail 'Existing .env.pilot is required; it will never be generated by the updater.'
exec 9>/opt/.omnicrm-pilot-update.lock
flock -n 9 || fail 'Another pilot update or rollback is running.'
docker info >/dev/null 2>&1 || fail 'Docker daemon is unavailable.'
docker compose version >/dev/null 2>&1 || fail 'Docker Compose is unavailable.'
if [ -n "${DOCKER_CONTEXT:-}" ]; then
  endpoint="$(docker context inspect "$DOCKER_CONTEXT" --format '{{(index .Endpoints "docker").Host}}')"
elif [ -n "${DOCKER_HOST:-}" ]; then
  endpoint="$DOCKER_HOST"
else
  endpoint="$(docker context inspect --format '{{(index .Endpoints "docker").Host}}')"
fi
case "$endpoint" in unix://*) ;; *) fail 'Use the local Docker Engine on this server.' ;; esac
compose=(env -u LOCAL_PORT -u DATABASE_URL -u ENCRYPTION_KEY -u JWT_SECRET -u WAHA_API_KEY -u POSTGRES_PASSWORD -u SMS_GATEWAY_URL -u WAHA_IMAGE -u TELEGRAM_PROXY_URL docker compose --project-name omnicrm-pilot --env-file "$target/.env.pilot" -f "$target/compose.pilot.yaml")
pinned_waha_image='devlikeapro/waha:noweb-2026.9.2@sha256:be61f8cd7774ab22bd1b755cbc539f98d71d81d5ca83555fdddfa4fddd7924e1'
# Inspect only option-match booleans, image ID and mounts; never emit environment values.
waha_inspect_format='{{$default := false}}{{$target := false}}{{$custom := false}}{{$proxy := false}}{{range .Config.Env}}{{$parts := split . "="}}{{$key := index $parts 0}}{{if eq $key "NODE_OPTIONS"}}{{if eq . "NODE_OPTIONS=--max-old-space-size=16384"}}{{$default = true}}{{else if eq . "NODE_OPTIONS=--max-old-space-size=16384 --dns-result-order=ipv4first --no-network-family-autoselection"}}{{$target = true}}{{else}}{{$custom = true}}{{end}}{{end}}{{if or (eq $key "WHATSAPP_PROXY_SERVER") (eq $key "WHATSAPP_PROXY_SERVER_LIST") (eq $key "WAHA_PROXY") (eq $key "HTTP_PROXY") (eq $key "HTTPS_PROXY") (eq $key "ALL_PROXY") (eq $key "http_proxy") (eq $key "https_proxy") (eq $key "all_proxy")}}{{if ne . (printf "%s=" $key)}}{{$proxy = true}}{{end}}{{end}}{{end}}{"image":{{json .Image}},"mounts":{{json .Mounts}},"node_default":{{$default}},"node_target":{{$target}},"node_custom":{{$custom}},"proxy_configured":{{$proxy}}}'
waha_runtime() {
  local id
  id="$("${compose[@]}" ps --all -q waha)"
  [ -n "$id" ] || return 1
  docker inspect --format "$waha_inspect_format" "$id"
}
verify_waha_runtime() {
  waha_runtime | python3 "$backup/control.py" waha-check "$target" "$backup/waha-runtime.json" "$1"
}

# A previous backup keeps this helper and rollback entry point outside the app tree.
if [ "${1:-}" = --rollback ]; then
  backup="${2:?Backup directory is required}"
  case "$backup" in "$backup_root"/*) ;; *) fail 'Rollback must use a backup made by this updater.' ;; esac
  [ -d "$backup" ] && [ ! -L "$backup" ] || fail 'Backup directory is missing or is a symlink.'
  [ "$(realpath "$backup")" = "$backup" ] || fail 'Use the canonical backup directory without traversal.'
  [ -f "$backup/complete" ] || fail 'This backup was not completed before cutover.'
  old_image="$(cat "$backup/old-image-id")"
  [[ "$old_image" =~ ^sha256:[a-f0-9]{64}$ ]] || fail 'Invalid saved image identifier.'
  docker image inspect "$old_image" >/dev/null || fail 'Previous image is unavailable; do not delete rollback images.'
  # Validate all source/backup paths before stopping the application.
  python3 "$backup/control.py" restore-check "$target" "$backup"
  if [ -f "$backup/requires-waha-recreate" ]; then
    verify_waha_runtime either
  fi
  "${compose[@]}" stop --timeout 60 api worker
  python3 "$backup/control.py" restore "$target" "$backup"
  docker image tag "$old_image" omnicrm:pilot
  if [ -f "$backup/requires-waha-recreate" ]; then
    "${compose[@]}" up -d --no-deps --no-build --pull never --wait --wait-timeout 180 waha
    verify_waha_runtime default
  fi
  "${compose[@]}" up -d --no-deps --no-build --wait --wait-timeout 180 api worker
  printf '%s\n' 'ROLLBACK_OK — previous source/image restored; database contents and additive migrations retained.'
  bash "$target/scripts/server_pilot.sh" status
  exit 0
fi
archive="${1:?Verified source archive is required}"
expected="${2:?Expected archive SHA-256 is required}"
[[ "$expected" =~ ^[a-f0-9]{64}$ ]] || fail 'Invalid archive SHA-256.'
[ -f "$archive" ] || fail 'Source archive is missing.'
[ "$(sha256sum "$archive" | awk '{print $1}')" = "$expected" ] || fail 'Archive checksum mismatch.'
[ ! -L "$backup_root" ] || fail 'Backup root must not be a symlink.'
mkdir -p -m 700 "$backup_root"
[ "$(stat -c %u "$backup_root")" = 0 ] && [ "$(stat -c %a "$backup_root")" = 700 ] || fail 'Backup root must be owned by root with mode 0700.'
for filesystem in /opt "$(docker info --format '{{.DockerRootDir}}')"; do
  available_kb="$(df -Pk "$filesystem" | awk 'NR == 2 {print $4}')"
  [[ "$available_kb" =~ ^[0-9]+$ ]] && [ "$available_kb" -ge 4194304 ] || fail 'At least 4 GiB free is required for the candidate image and private backup.'
done
stage="$(mktemp -d /opt/omnicrm-pilot-update.stage.XXXXXXXX)"
backup=''
cutover=0
source_changed=0
waha_change_started=0
cleanup() {
  local result=$?
  trap - EXIT INT TERM
  if [ "$result" -ne 0 ] && [ "$cutover" = 1 ]; then
    printf '\nUpdate failed; restoring previous application source and image.\n' >&2
    local recovered=1
    if [ "$source_changed" = 1 ]; then
      python3 "$backup/control.py" restore "$target" "$backup" || recovered=0
    fi
    docker image tag "$old_image" omnicrm:pilot || recovered=0
    if [ "$recovered" = 1 ] && [ "$waha_change_started" = 1 ]; then
      "${compose[@]}" up -d --no-deps --no-build --pull never --wait --wait-timeout 180 waha || recovered=0
      if [ "$recovered" = 1 ]; then
        verify_waha_runtime default || recovered=0
      fi
    fi
    if [ "$recovered" = 1 ]; then
      "${compose[@]}" up -d --no-deps --no-build --wait --wait-timeout 180 api worker || recovered=0
    fi
    if [ "$recovered" = 1 ]; then
      printf '%s\n' 'Previous application restarted. Database was NOT restored; additive schema changes, if committed, remain.' >&2
    else
      printf 'Automatic application recovery did not finish. Keep all data; recovery command: bash %q/rollback.sh\n' "$backup" >&2
    fi
  fi
  # stage contains only validated source and temporary Compose config; no persistent data.
  rm -rf -- "$stage"
  exit "$result"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
cat > "$stage/control.py" <<'PY'
import hashlib, json, os, re, stat, sys, tarfile, tempfile
from pathlib import Path, PurePosixPath

TOP = {'.dockerignore', '.gitignore', 'Dockerfile', 'LICENSE', 'README.md', 'Start.command', 'Stop.command', 'requirements.in', 'requirements.lock', 'compose.yaml', 'compose.local.yaml', 'compose.pilot.yaml'}
PREFIX = {'app', 'web', 'scripts', 'docs', 'tests'}
MANIFEST = 'docs/source-manifest.json'
PINNED_WAHA_IMAGE = 'devlikeapro/waha:noweb-2026.9.2@sha256:be61f8cd7774ab22bd1b755cbc539f98d71d81d5ca83555fdddfa4fddd7924e1'
WAHA_IPV4_OPTIONS = '--max-old-space-size=16384 --dns-result-order=ipv4first --no-network-family-autoselection'

def fail(message):
    raise SystemExit(message)

def waha_ipv4_transition(old, new):
    if old.get('image') != PINNED_WAHA_IMAGE or new.get('image') != PINNED_WAHA_IMAGE:
        return False
    before, after = old.get('environment'), new.get('environment')
    if not isinstance(before, dict) or not isinstance(after, dict):
        return False
    if 'NODE_OPTIONS' in before or after.get('NODE_OPTIONS') != WAHA_IPV4_OPTIONS:
        return False
    stripped = dict(after)
    stripped.pop('NODE_OPTIONS')
    return old == {**new, 'environment': stripped}

def waha_snapshot(value, options):
    if not isinstance(value, dict) or not re.fullmatch(r'sha256:[a-f0-9]{64}', str(value.get('image', ''))):
        fail('WAHA runtime image identity is invalid.')
    if value.get('proxy_configured') is not False or value.get('node_custom') is not False:
        fail('WAHA has custom runtime options or proxy routing; inspect before this targeted repair.')
    default, target = value.get('node_default') is True, value.get('node_target') is True
    if default == target or (options == 'default' and not default) or (options == 'target' and not target):
        fail('WAHA runtime NODE_OPTIONS does not match the reviewed transition.')
    mounts = value.get('mounts')
    if not isinstance(mounts, list):
        fail('WAHA runtime mounts are unavailable.')
    volumes = []
    for mount in mounts:
        if not isinstance(mount, dict) or mount.get('Type') not in {'volume', 'tmpfs'}:
            fail('Unexpected WAHA runtime mount type.')
        if mount['Type'] == 'volume':
            volumes.append({key: mount.get(key) for key in ('Name', 'Destination', 'RW')})
    expected = [
        {'Name': 'omnicrm-pilot_waha-media', 'Destination': '/app/.media', 'RW': True},
        {'Name': 'omnicrm-pilot_waha-sessions', 'Destination': '/app/.sessions', 'RW': True},
    ]
    if sorted(volumes, key=lambda item: str(item['Name'])) != expected:
        fail('WAHA persistent volumes differ from the existing private pilot.')
    return {'image': value['image'], 'volumes': expected}

def safe(name):
    if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_./-]+', name):
        fail('Invalid source path')
    p = PurePosixPath(name)
    if p.is_absolute() or str(p) != name or any(x in ('', '.', '..') for x in p.parts):
        fail('Unsafe source path')
    if len(p.parts) == 1:
        if name not in TOP:
            fail('Unknown top-level source path: ' + name)
    elif p.parts[0] not in PREFIX or any(x.startswith('.') for x in p.parts):
        fail('Unowned or hidden source path: ' + name)
    if any(x in {'node_modules', '__pycache__', 'backups', 'artifacts'} for x in p.parts) or name.endswith(('.pyc', '.session', '.db', '.sqlite', '.pem', '.key', '.har')):
        fail('Non-source or sensitive file refused: ' + name)
    return name

def digest(data):
    return hashlib.sha256(data).hexdigest()

def manifest(data):
    def unique(items):
        result = {}
        for key, value in items:
            if key in result:
                fail('Duplicate manifest key')
            result[key] = value
        return result
    result = json.loads(data, object_pairs_hook=unique)
    if not isinstance(result, dict) or not result or len(result) > 2000:
        fail('Invalid source manifest')
    for name, value in result.items():
        safe(name)
        if name == MANIFEST or not isinstance(value, str) or not re.fullmatch('[a-f0-9]{64}', value):
            fail('Invalid manifest entry')
    return result

def checked(root, name):
    safe(name)
    current = root
    for part in PurePosixPath(name).parts:
        current = current / part
        if current.is_symlink():
            fail('Refusing symlink in source path: ' + name)
    if current.exists() and not current.is_file():
        fail('Source file is not a regular file: ' + name)
    return current

def load_source(root):
    mpath = checked(root, MANIFEST)
    entries = manifest(mpath.read_bytes())
    for name, expected in entries.items():
        p = checked(root, name)
        if not p.is_file() or digest(p.read_bytes()) != expected:
            fail('Source modified or missing; update stopped before replacing it: ' + name)
    return entries

def atomic_copy(source, destination):
    destination.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, temporary = tempfile.mkstemp(prefix='.omnicrm-update-', dir=destination.parent)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(source.read_bytes())
        os.chmod(temporary, stat.S_IMODE(source.stat().st_mode) & 0o777)
        os.replace(temporary, destination)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)

def restore_check(root, backup):
    old = load_source(backup / 'source')
    new_bytes = (backup / 'new-manifest.json').read_bytes()
    new = manifest(new_bytes)
    listing = json.loads((backup / 'replaced-paths.json').read_text())
    if not isinstance(listing, list) or len(listing) > 4001:
        fail('Invalid backup file list')
    for name in set(listing) | set(old) | {MANIFEST}:
        path = checked(root, name)
        if path.exists():
            allowed = {old.get(name), new.get(name)}
            if name == MANIFEST:
                allowed = {digest(new_bytes), digest((backup / 'source' / MANIFEST).read_bytes())}
            if digest(path.read_bytes()) not in allowed:
                fail('Locally changed source blocks safe rollback: ' + name)
    return old, listing

operation = sys.argv[1]
root = Path(sys.argv[2])
if operation == 'extract':
    archive, stage = Path(sys.argv[3]), Path(sys.argv[4])
    contents = {}
    total = 0
    with tarfile.open(archive, 'r:gz') as tf:
        for item in tf:
            # Directory entries are not needed; rejecting links/devices also avoids extraction attacks.
            if item.isdir():
                if item.name.rstrip('/') == 'omnicrm':
                    continue
                name = item.name.rstrip('/')
                if not name.startswith('omnicrm/') or '..' in PurePosixPath(name).parts or PurePosixPath(name).is_absolute():
                    fail('Unsafe archive directory')
                continue
            if not item.isfile() or not item.name.startswith('omnicrm/'):
                fail('Archive must contain regular source files only')
            name = safe(item.name[len('omnicrm/'):])
            if name in contents or len(contents) >= 2001 or item.size > 64 * 1024 * 1024:
                fail('Duplicate or oversized source archive entry')
            total += item.size
            if total > 256 * 1024 * 1024:
                fail('Source archive is too large')
            contents[name] = tf.extractfile(item).read()
    if MANIFEST not in contents:
        fail('Archive source manifest is missing')
    entries = manifest(contents[MANIFEST])
    if set(contents) != set(entries) | {MANIFEST}:
        fail('Archive contents differ from manifest')
    for name, expected in entries.items():
        if digest(contents[name]) != expected:
            fail('Source file checksum mismatch: ' + name)
    old = load_source(root)
    for name in entries.keys() - old.keys():
        if checked(root, name).exists():
            fail('New source collides with an untracked local file: ' + name)
    for name, data in contents.items():
        p = checked(stage, name)
        p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        p.write_bytes(data)
        p.chmod(0o755 if name.lower().endswith(('.sh', '.command')) else 0o644)
    print('Archive paths, SHA-256 manifest and unmodified installed source validated.')
elif operation == 'config':
    old, new = (json.loads(Path(p).read_text()) for p in sys.argv[3:5])
    recreate_waha = False
    for field in ('name', 'volumes', 'networks'):
        if old.get(field) != new.get(field):
            fail('Update would change persistent Docker infrastructure: ' + field)
    for name in ('postgres', 'waha', 'waha-volume-init'):
        if old['services'][name] != new['services'][name]:
            if name == 'waha' and waha_ipv4_transition(old['services'][name], new['services'][name]):
                recreate_waha = True
            else:
                fail('Update would change a persistent service: ' + name)
    if old['services']['api']['ports'] != new['services']['api']['ports']:
        fail('Update would change the saved API port')
    ports = new['services']['api']['ports']
    if len(ports) != 1 or ports[0]['host_ip'] != '127.0.0.1':
        fail('API must remain bound to loopback only')
    for name in ('api', 'worker', 'migrate'):
        env = new['services'][name]['environment']
        for key in ('DATABASE_URL', 'ENCRYPTION_KEY', 'JWT_SECRET', 'WAHA_API_KEY'):
            if env[key] != old['services'][name]['environment'][key]:
                fail('Update would change persistent credentials')
        if env.get('LOCAL_TEST_MODE') != 'true' or env.get('DEMO_MODE') != 'false':
            fail('Update is not the private pilot profile')
        if new['services'][name]['image'] != 'omnicrm:pilot':
            fail('Unexpected application image name')
    if recreate_waha and len(sys.argv) < 6:
        fail('Targeted WAHA recreation requires an explicit update plan.')
    if len(sys.argv) >= 6:
        Path(sys.argv[5]).write_text('1' if recreate_waha else '0')
    print('Saved API port, credentials, PostgreSQL and persistent volumes are unchanged.')
    if recreate_waha:
        print('One pinned-WAHA IPv4 settings transition requires a targeted gateway recreation.')
elif operation in ('waha-save', 'waha-check'):
    destination = Path(sys.argv[3])
    options = 'default' if operation == 'waha-save' else sys.argv[4]
    if options not in {'default', 'target', 'either'}:
        fail('Unknown WAHA snapshot validation mode.')
    snapshot = waha_snapshot(json.load(sys.stdin), options)
    if operation == 'waha-save':
        if snapshot['image'] != sys.argv[4]:
            fail('Running WAHA image differs from the approved pinned image.')
        destination.write_text(json.dumps(snapshot, sort_keys=True))
    elif json.loads(destination.read_text()) != snapshot:
        fail('WAHA image or persistent volume identity changed unexpectedly.')
elif operation == 'backup':
    stage, backup = Path(sys.argv[3]), Path(sys.argv[4])
    old, new = load_source(root), load_source(stage)
    for name in set(old) | {MANIFEST}:
        atomic_copy(checked(root, name), checked(backup / 'source', name))
    (backup / 'new-manifest.json').write_bytes((stage / MANIFEST).read_bytes())
    (backup / 'replaced-paths.json').write_text(json.dumps(sorted(set(old) | set(new) | {MANIFEST})))
elif operation == 'install':
    stage, backup = Path(sys.argv[3]), Path(sys.argv[4])
    old, new = load_source(root), load_source(stage)
    # Validate all paths before the first replacement; local extras remain untouched.
    for name in set(old) | set(new) | {MANIFEST}:
        checked(root, name)
    for name in new:
        atomic_copy(checked(stage, name), checked(root, name))
    for name in old.keys() - new.keys():
        checked(root, name).unlink()
    atomic_copy(checked(stage, MANIFEST), checked(root, MANIFEST))
elif operation in ('restore', 'restore-check'):
    backup = Path(sys.argv[3])
    old, listing = restore_check(root, backup)
    if operation == 'restore':
        for name in set(old) | {MANIFEST}:
            atomic_copy(checked(backup / 'source', name), checked(root, name))
        for name in set(listing) - set(old) - {MANIFEST}:
            checked(root, name).unlink(missing_ok=True)
else:
    fail('Unknown updater operation')
PY
python3 "$stage/control.py" extract "$target" "$archive" "$stage"
new_compose=(env -u LOCAL_PORT -u DATABASE_URL -u ENCRYPTION_KEY -u JWT_SECRET -u WAHA_API_KEY -u POSTGRES_PASSWORD -u SMS_GATEWAY_URL -u WAHA_IMAGE -u TELEGRAM_PROXY_URL docker compose --project-name omnicrm-pilot --env-file "$target/.env.pilot" -f "$stage/compose.pilot.yaml")
"${compose[@]}" config --format json > "$stage/old-config.json"
"${new_compose[@]}" config --format json > "$stage/new-config.json"
python3 "$stage/control.py" config "$target" "$stage/old-config.json" "$stage/new-config.json" "$stage/waha-plan"
requires_waha_recreate="$(cat "$stage/waha-plan")"
case "$requires_waha_recreate" in 0|1) ;; *) fail 'Invalid WAHA update plan.' ;; esac
# Resolved Compose JSON contains credentials; remove it before copying source/creating backups.
rm -- "$stage/old-config.json" "$stage/new-config.json"
api_id="$("${compose[@]}" ps -q api)"
worker_id="$("${compose[@]}" ps -q worker)"
postgres_id="$("${compose[@]}" ps -q postgres)"
waha_id="$("${compose[@]}" ps -q waha)"
[ -n "$api_id" ] && [ -n "$worker_id" ] && [ -n "$postgres_id" ] && [ -n "$waha_id" ] || fail 'Existing API, worker, PostgreSQL and WAHA must be running before an update.'
if [ "$requires_waha_recreate" = 1 ]; then
  expected_waha_image="$(docker image inspect --format '{{.Id}}' "$pinned_waha_image")"
  waha_runtime | python3 "$stage/control.py" waha-save "$target" "$stage/waha-runtime.json" "$expected_waha_image"
fi
old_image="$(docker inspect --format '{{.Image}}' "$api_id")"
[ "$(docker inspect --format '{{.Image}}' "$worker_id")" = "$old_image" ] || fail 'API and worker use different images; inspect the existing deployment first.'
